export class SpriteError extends Error {}

/** Checks a sprite's grid: equal row lengths and only the allowed characters. */
export function checkSprite(name: string, sprite: Sprite): void {
  const width = sprite.rows[0]?.length ?? 0
  sprite.rows.forEach((row, y) => {
    if (row.length !== width) {
      throw new SpriteError(`Sprite "${name}" row ${y} is ${row.length} wide, expected ${width}`)
    }
    const bad = /[^.0-3]/.exec(row)
    if (bad) throw new SpriteError(`Sprite "${name}" row ${y} has "${bad[0]}" (use . or 0–3)`)
  })
}

/**
 * The sprite as an SVG string. Runs of one shade on a row become a single
 * <rect>, which keeps the markup small. Shades are classes (s0–s3) coloured by
 * the game's palette CSS. `label` gives the image an accessible name; without
 * one it's hidden from screen readers.
 */
export function spriteSvg(name: string, label?: string): string {
  const sprite = SPRITES[name]
  if (!sprite) throw new SpriteError(`Unknown sprite "${name}"`)
  checkSprite(name, sprite)
  const height = sprite.rows.length
  const width = sprite.rows[0].length
  const rects: string[] = []
  sprite.rows.forEach((row, y) => {
    let x = 0
    while (x < width) {
      const shade = row[x]
      let end = x + 1
      while (end < width && row[end] === shade) end++
      if (shade !== '.') {
        rects.push(`<rect class="s${shade}" x="${x}" y="${y}" width="${end - x}" height="1"/>`)
      }
      x = end
    }
  })
  const a11y = label
    ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"`
    : 'aria-hidden="true"'
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" ` +
    `width="${width}" height="${height}" shape-rendering="crispEdges" ${a11y}>` +
    rects.join('') +
    '</svg>'
  )
}
